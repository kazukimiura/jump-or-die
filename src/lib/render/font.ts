export type FontId = 'F3X5' | 'F5X7' | 'KANA'

/** 字送り（px・等倍） */
export const ADVANCE: Record<FontId, number> = { F3X5: 4, F5X7: 6, KANA: 8 }
/** 行送り（px・等倍） */
export const LINE_HEIGHT: Record<FontId, number> = { F3X5: 7, F5X7: 9, KANA: 10 }
/** かな行に混ざる半角（数字・スペース）の字送り */
export const KANA_HALF_ADVANCE = 4
/** かな 1 行の最大幅（全角 12.0） */
export const KANA_MAX_WIDTH = 96

interface GlyphRect {
  x: number
  y: number
  w: number
  h: number
}

const FONT_ATLAS_W = 256
const glyphRects = new Map<string, GlyphRect>()
const fontAtlases: (HTMLCanvasElement | null)[] = [null, null, null, null]

/** ビットマスク → 行文字列 */
function maskRows(mask: readonly number[], w: number): string[] {
  return mask.map((bits) => {
    let s = ''
    for (let x = 0; x < w; x++) s += (bits >> (w - 1 - x)) & 1 ? '1' : '.'
    return s
  })
}

function glyphSource(): Map<string, string[]> {
  const src = new Map<string, string[]>()
  for (const [ch, mask] of Object.entries(FONT_3X5)) src.set(`3|${ch}`, maskRows(mask, 3))
  for (const [ch, mask] of Object.entries(FONT_5X7)) src.set(`5|${ch}`, maskRows(mask, 5))
  for (const [ch, rows] of Object.entries(FONT_KANA)) src.set(`K|${ch}`, [...rows])
  return src
}

let sourceCache: Map<string, string[]> | null = null

function layoutGlyphs(): { src: Map<string, string[]>; height: number } {
  if (!sourceCache) sourceCache = glyphSource()
  const src = sourceCache
  if (glyphRects.size > 0) {
    let max = 0
    for (const r of glyphRects.values()) max = Math.max(max, r.y + r.h)
    return { src, height: max + 1 }
  }
  let cx = 1
  let cy = 1
  let shelfH = 0
  for (const [key, rows] of src) {
    const w = rows[0].length
    const h = rows.length
    if (cx + w + 1 > FONT_ATLAS_W) {
      cx = 1
      cy += shelfH + 1
      shelfH = 0
    }
    glyphRects.set(key, { x: cx, y: cy, w, h })
    cx += w + 1
    shelfH = Math.max(shelfH, h)
  }
  return { src, height: cy + shelfH + 1 }
}

/**
 * 起動時に 1 度だけ呼ぶ。階調ごとに 1 枚ずつ、計 4 枚のフォントアトラスを焼く。
 * 階調の切り替えは「どのアトラスから切り出すか」だけで済み、プレイ中のピクセル操作が要らない。
 */
export function initFont(): void {
  if (fontAtlases[0]) return
  const { src, height } = layoutGlyphs()
  const tones: readonly Tone[] = [1, 2, 3, 4]
  for (const t of tones) {
    const cv = createCanvas(FONT_ATLAS_W, height)
    const g = cv.getContext('2d')
    if (!g) throw new Error('2d context unavailable')
    g.imageSmoothingEnabled = false
    g.fillStyle = PALETTE[t - 1]
    for (const [key, rect] of glyphRects) {
      const rows = src.get(key)
      if (!rows) continue
      for (let y = 0; y < rows.length; y++) {
        const row = rows[y]
        for (let x = 0; x < row.length; x++) {
          if (row[x] === '.') continue
          g.fillRect(rect.x + x, rect.y + y, 1, 1)
        }
      }
    }
    fontAtlases[t - 1] = cv
  }
}

function atlasFor(tone: Tone): HTMLCanvasElement {
  if (!fontAtlases[tone - 1]) initFont()
  return fontAtlases[tone - 1] as HTMLCanvasElement
}

const warned = new Set<string>()
function warnOnce(msg: string): void {
  if (warned.has(msg)) return
  warned.add(msg)
  if (process.env.NODE_ENV !== 'production') console.warn(`[font] ${msg}`)
}

function isHalfWidth(ch: string): boolean {
  return ch.charCodeAt(0) < 0x80
}

function glyphKey(font: FontId, ch: string): string {
  if (font === 'F3X5') return `3|${ch}`
  if (font === 'F5X7') return `5|${ch}`
  return isHalfWidth(ch) ? `3|${ch}` : `K|${ch}`
}

/** 文字 1 個の字送り（等倍） */
function advanceOf(font: FontId, ch: string): number {
  if (font === 'KANA') return isHalfWidth(ch) ? KANA_HALF_ADVANCE : ADVANCE.KANA
  return ADVANCE[font]
}

/** 文字列の描画幅（px）。align の計算と幅の検算に使う */
export function measureText(text: string, font: FontId, scale = 1): number {
  let w = 0
  for (const ch of text) w += advanceOf(font, ch)
  return w * scale
}

export interface TextOptions {
  font: FontId
  tone: Tone
  /** 整数倍のみ。見出しは 2（10×14）。3 倍以上は使わない */
  scale?: 1 | 2
  /** left = x が左端 / center = x が中心 / right = x が右端（最終画素の 1px 右） */
  align?: 'left' | 'center' | 'right'
}

/**
 * 文字列を描く。座標は必ず整数へ丸めて描画する。
 * かなの 1 行が 96px を超える場合は **描画せず**、開発ビルドで警告する（スタイルガイド §4-4）。
 */
export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  opts: TextOptions,
): void {
  const { font, tone } = opts
  const scale = opts.scale ?? 1
  const align = opts.align ?? 'left'
  const width = measureText(text, font, scale)

  if (font === 'KANA' && width > KANA_MAX_WIDTH * scale) {
    warnOnce(`かな 1 行が ${KANA_MAX_WIDTH * scale}px を超えました: "${text}" (${width}px)`)
    return
  }

  let cx = Math.round(align === 'center' ? x - width / 2 : align === 'right' ? x - width : x)
  const cy = Math.round(y)
  const atlas = atlasFor(tone)

  for (const ch of text) {
    const adv = advanceOf(font, ch) * scale
    if (ch === ' ') {
      cx += adv
      continue
    }
    const rect = glyphRects.get(glyphKey(font, ch))
    if (!rect) {
      warnOnce(`グリフがありません: "${ch}"（文脈 恵に差し戻すこと）`)
      cx += adv
      continue
    }
    // かな行に混ざる半角数字は FONT_3x5 をセル下寄せ（y2–6）で置き、ベースラインを合わせる
    const dy = font === 'KANA' && isHalfWidth(ch) ? cy + 2 * scale : cy
    ctx.drawImage(atlas, rect.x, rect.y, rect.w, rect.h, cx, dy, rect.w * scale, rect.h * scale)
    cx += adv
  }
}

/** 収録グリフ数の検査（3x5 = 39 / 5x7 = 43 / かな = 82。いずれも半角スペースを除く） */
export function assertFonts(): string[] {
  const errors: string[] = []
  const count3 = Object.keys(FONT_3X5).length - 1
  const count5 = Object.keys(FONT_5X7).length - 1
  const countK = Object.keys(FONT_KANA).length
  // 宣言は 39 / 43 / 82。実装では 3x5 に 2 字、かなに 5 字を増補している（冒頭の申し送り参照）
  if (count3 !== 45) errors.push(`FONT_3x5 の収録字数が ${count3}（39 ＋ 増補 6 ＝ 45）`)
  if (count5 !== 46) errors.push(`FONT_5x7 の収録字数が ${count5}（43 ＋ 増補 3 ＝ 46）`)
  if (countK !== 87) errors.push(`FONT_KANA_8x8 の収録字数が ${countK}（82 ＋ 増補 5 ＝ 87）`)
  for (const [ch, mask] of Object.entries(FONT_3X5)) {
    if (mask.length !== 5) errors.push(`FONT_3x5 "${ch}": 行数 ${mask.length} ≠ 5`)
    if (mask.some((m) => m > 0b111)) errors.push(`FONT_3x5 "${ch}": 3bit を超えた行がある`)
  }
  for (const [ch, mask] of Object.entries(FONT_5X7)) {
    if (mask.length !== 7) errors.push(`FONT_5x7 "${ch}": 行数 ${mask.length} ≠ 7`)
    if (mask.some((m) => m > 0b11111)) errors.push(`FONT_5x7 "${ch}": 5bit を超えた行がある`)
  }
  for (const [ch, rows] of Object.entries(FONT_KANA)) {
    if (rows.length !== 7) errors.push(`FONT_KANA "${ch}": 行数 ${rows.length} ≠ 7`)
    rows.forEach((r, i) => {
      if (r.length !== 7) errors.push(`FONT_KANA "${ch}": y${i} の文字数 ${r.length} ≠ 7`)
    })
  }
  return errors
}
