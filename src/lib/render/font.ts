/**
 * font.ts — ビットマップフォント 3 系統と文字列描画
 *
 * 出典: スタイルガイド §4、ドット素材指示書 §6
 *
 * 絶対制約:
 *   - **Web フォント／システムフォントを一切使わない。** 全グリフを自前のドットで持つ
 *   - 英字はすべて大文字。小文字グリフは作らない（`toUpperCase()` も掛けない）
 *   - 画面内の日本語は漢字ゼロ・分かち書き。**分かち書きの半角スペース 4px を詰めない**
 *   - かな 1 行の最大幅は 96px。超えたら描画せず開発ビルドで警告を出す
 *   - 濁音・半濁音は専用グリフ（清音＋濁点の重ね描きはしない）。
 *     本モジュールでは「本体を左へ 1px 詰めて右上に専用の記号を焼く」形で 15 字を生成する
 *
 * | 名称        | セル | 字送り | 行送り | 用途                          |
 * |------------|------|--------|--------|-------------------------------|
 * | FONT_3x5   | 3×5  | 4px    | 7px    | HUD・副次情報・かな行内の半角数字 |
 * | FONT_5x7   | 5×7  | 6px    | 9px    | 英字の標準・数値・ラベル         |
 * | FONT_KANA  | 8×8  | 8px    | 10px   | 日本語 1 行（本体 7×7）         |
 *
 * 見出しは FONT_5x7 の整数 2 倍拡大（10×14 / 字送り 12px）。3 倍以上は使わない。
 *
 * --- 記号グリフのベースライン規則（指示書 §6-2 改訂 R4・全フォント共通）------------
 * | 種別     | 字                        | FONT_3x5 | FONT_5x7 |
 * | 全高     | A–Z / 0–9 / `%` / `/`     | y0–y4    | y0–y6    |
 * | 中央揃え | `×` `:` `=` `-`           | y1–y3    | y2–y4    |
 * | 下端揃え | `.` `,`                   | y4       | y6       |
 * 中央揃えの記号は上下に必ず等しい余白を残す。
 * ----------------------------------------------------------------------------
 *
 * --- 素材指示書の収録字数に対する増補（采配承認済み・R4 / R6 として文書へ反映）-----
 * 指示書 §6-2 は FONT_3x5 を 39 字（A–Z / 0–9 / . % ×）と宣言しているが、
 * スタイルガイド §6-1 が 3x5 で指定している `SPACE / CLICK` に `/` が、
 * UIテキスト 11-2 が 3x5 で指定しているクリア済み枠の `00:41.32` に `:` が要る。
 * 描画できないままにはできないため **`/` `:` `=`（`HOLD = PRACTICE` 用）の 3 字を増補**した。
 *
 * さらに、**R4 の記号ベースライン規則表に載っているのに収録表から漏れていた記号**を
 * 両フォントへ補った。`-` は STAGE SELECT の未プレイ枠に出る `--` で実際に使われており、
 * 欠けていると開発ビルドに警告が出たうえ **本番では黙って空欄になる**。
 * 同じ事故を他画面で起こさないため、規則表の記号集合 { `.` `,` `%` `×` `/` `:` `=` `-` } を
 * 両フォントで揃えた（FONT_3x5 に `-` `,` `!` → 計 45 字／FONT_5x7 に `-` `=` `,` → 計 46 字）。
 * ※ `,` はグリフを持つが **3 桁区切りのカンマは全画面で使用禁止**（UIテキスト 15-2）。
 *   黙って消えるより見えて落ちるほうが検査で捕まるため、安全網として焼いてあるだけである。
 *
 * 指示書 §6-3 は濁音・半濁音を 10 字（が ぎ ず ぜ だ ど ぶ べ ぼ ぽ）と宣言しているが、
 * UIテキスト 3章・14章の死亡メッセージ 36 本を実測したところ
 * **`で` `ば` `び` `ご` `じ` の 5 字が不足**していた（そこで／とばなかった／ゆびが／
 * うごきは／はじめの）。同じ作図方式で 5 字を増補した（計 87 字）。
 * ----------------------------------------------------------------------------
 *
 * React に依存しない純粋な TypeScript モジュール。
 */

